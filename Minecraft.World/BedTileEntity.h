#pragma once
using namespace std;

#include "TileEntity.h"

class Level;
class LevelSource;

// neoLegacy - Fancy Beds. ONE bed tile id and ONE bed item id for every bed in the game.
//
// A bed's tile data already uses all 4 bits (2 for the direction, 1 occupied, 1 head piece), so the bed's look can't
// live there. Same idea as ConcreteColorTileEntity / BannerTileEntity: both halves of a bed carry a tiny tile entity
// holding which bed it is, and BedRenderer draws it from that. The item form carries the same value as its aux.
//
//   0 .. 15   dye colors in the wool/block order  (white, orange, magenta, light blue, yellow, lime, pink, gray,
//             light gray, cyan, purple, blue, brown, green, red, black)
//   16        straw bed (single use, never sets the respawn point)
//
// A bed with no tile entity yet (generated by a village, placed by older code) gets one on demand with DEFAULT_VARIANT.
class BedTileEntity : public TileEntity
{
public:
	eINSTANCEOF GetType() { return eTYPE_BEDTILEENTITY; }
	static TileEntity *create() { return new BedTileEntity(); }

	static const int VARIANT_COUNT = 17;
	static const int VARIANT_STRAW = 16;
	static const int DEFAULT_VARIANT = 14;	// red, what the old single bed looked like

private:
	int variant;

public:
	BedTileEntity();
	virtual ~BedTileEntity() {}

	int getVariant() const { return variant; }
	void setVariant(int v) { variant = (v >= 0 && v < VARIANT_COUNT) ? v : DEFAULT_VARIANT; }
	bool isStraw() const { return variant == VARIANT_STRAW; }

	// Variant of the bed at a position, or -1 when there is no BedTileEntity there.
	static int getVariantAt(LevelSource *level, int x, int y, int z);
	// Sets it and marks the tile entity changed so it is saved and re-sent to clients.
	static void setVariantAt(Level *level, int x, int y, int z, int variant);

	virtual void save(CompoundTag *tag);
	virtual void load(CompoundTag *tag);
	virtual shared_ptr<Packet> getUpdatePacket();
	virtual shared_ptr<TileEntity> clone();
};
