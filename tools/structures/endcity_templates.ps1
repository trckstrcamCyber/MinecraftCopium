$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
. (Join-Path $PSScriptRoot 'nbt.ps1')

$names = @(
    'base_floor', 'base_roof', 'bridge_end', 'bridge_gentle_stairs', 'bridge_piece', 'bridge_steep_stairs',
    'fat_tower_base', 'fat_tower_middle', 'fat_tower_top', 'second_floor', 'second_floor_2', 'second_roof',
    'ship', 'third_floor', 'third_floor_b', 'third_floor_c', 'third_roof', 'tower_base', 'tower_floor',
    'tower_piece', 'tower_top')

$out = New-Object System.Text.StringBuilder
[void]$out.AppendLine('// Generated by tools/structures/endcity_templates.ps1 from the Java 1.9 end city')
[void]$out.AppendLine('// templates. Do not edit by hand.')
[void]$out.AppendLine('#include "stdafx.h"')
[void]$out.AppendLine('#include "EndCityTemplates.h"')
[void]$out.AppendLine('')

$table = @()
foreach ($name in $names) {
    $n = Read-Nbt (Join-Path $PSScriptRoot "endcity\$name.nbt")
    $size = $n['size']
    $blocks = New-Object System.Collections.Generic.List[string]
    $extras = New-Object System.Collections.Generic.List[string]

    foreach ($b in $n['blocks']) {
        $p = $b['pos']
        $st = [int]$b['state']
        $id = $st -band 0xFFF
        $data = $st -shr 12
        $nbt = $null
        if ($b.Contains('nbt')) { $nbt = $b['nbt'] }

        if ($id -eq 255) {
            $marker = [string]$nbt['metadata']
            $kind = $null
            if ($marker.StartsWith('Chest')) { $kind = 'EXTRA_CHEST_LOOT' }
            elseif ($marker.StartsWith('Sentry')) { $kind = 'EXTRA_SENTRY' }
            elseif ($marker.StartsWith('Elytra')) { $kind = 'EXTRA_ELYTRA' }
            if ($kind) { $extras.Add("{$($p[0]),$($p[1]),$($p[2]),EndCityTemplates::$kind,0}") }
            # Like in actual LCE and even in java , structure blocks themselves should never placed.
            continue
        }
        elseif ($nbt -ne $null) {
            switch ([string]$nbt['id']) {
                'Banner' { $extras.Add("{$($p[0]),$($p[1]),$($p[2]),EndCityTemplates::EXTRA_BANNER,$($nbt['Base'])}") }
                'Skull' { $extras.Add("{$($p[0]),$($p[1]),$($p[2]),EndCityTemplates::EXTRA_SKULL,$($nbt['SkullType'])}") }
                'Cauldron' { $extras.Add("{$($p[0]),$($p[1]),$($p[2]),EndCityTemplates::EXTRA_HEALING_POTIONS,0}") }
            }
        }
        $blocks.Add("{$($p[0]),$($p[1]),$($p[2]),$id,$data}")
    }

    [void]$out.AppendLine("static const EndCityTemplates::Block s_${name}_blocks[] = {")
    for ($i = 0; $i -lt $blocks.Count; $i += 16) {
        $line = ($blocks.GetRange($i, [Math]::Min(16, $blocks.Count - $i)) -join ',')
        [void]$out.AppendLine("`t$line,")
    }
    [void]$out.AppendLine('};')
    $extraRef = 'nullptr, 0'
    if ($extras.Count -gt 0) {
        [void]$out.AppendLine("static const EndCityTemplates::Extra s_${name}_extras[] = {")
        [void]$out.AppendLine("`t" + ($extras -join ',') + ',')
        [void]$out.AppendLine('};')
        $extraRef = "s_${name}_extras, $($extras.Count)"
    }
    [void]$out.AppendLine('')
    $table += "`t{ L`"$name`", $($size[0]), $($size[1]), $($size[2]), s_${name}_blocks, $($blocks.Count), $extraRef },"
}

[void]$out.AppendLine('const EndCityTemplates::Template EndCityTemplates::TEMPLATES[EndCityTemplates::COUNT] =')
[void]$out.AppendLine('{')
foreach ($t in $table) { [void]$out.AppendLine($t) }
[void]$out.AppendLine('};')

$text = $out.ToString() -replace "`r?`n", "`r`n"
[System.IO.File]::WriteAllText((Join-Path $root 'Minecraft.World\EndCityTemplates.cpp'), $text, (New-Object System.Text.UTF8Encoding($false)))
Write-Host "Wrote $($names.Count) templates"
